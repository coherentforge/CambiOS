"""
check-fail-open: enforcement fails closed (CLAUDE.md § Formal
Verification; ADR-006 § Divergence 2026-10-28).

A security-first kernel has no mode in which the enforcer's absence
grants permission. The policy upcall ran fail-open for months without
anyone noticing, because the outcome was always Allow (2026-10-27). This
lint makes any new fail-open path — in code or in the comment that
describes it — a conscious, reviewed decision rather than a reflex.

Scope: kernel and user-space Rust sources (`src/`, `user/*/src/`,
`cambios-abi/src/`, `cambios-manifest/src/`). Historical ADR prose is out
of scope — the Divergence appendices are where superseded designs are
remembered.

Patterns flagged (case-insensitive, comments included — the prose is the
point):
  fail-open / fail_open / fail open / fails open
  falls back to Allow / fall back to permissive
  permissive default / permissive policy
  default(s/ed) to Allow

Exemption: a `// FAIL_OPEN_OK: <reason>` comment within 3 lines above (or
on the same line) — for the structural case where there is no one to ask
yet (init before the policy service exists) or a test that exercises the
deny path by naming what it rejects.

Baseline exemptions live in `tools/check-fail-open-baseline.txt`, one
`path:line:pattern` record per line. Expected state: empty. Any new line
is a regression relative to the fail-closed decision and must carry its
own argument in review.

Exit status:
  0 — no new sites
  1 — new sites flagged
  2 — repo root not found or baseline unreadable
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE_PATH = ROOT / "tools" / "check-fail-open-baseline.txt"

PATTERNS = [
    ("fail-open", re.compile(r"\bfail[- _]?open\b", re.IGNORECASE)),
    ("fails-open", re.compile(r"\bfails open\b", re.IGNORECASE)),
    ("falls-back-to-allow", re.compile(r"\bfalls?\s+back\s+to\s+(allow|permissive)\b", re.IGNORECASE)),
    ("permissive-default", re.compile(r"\bpermissive\s+(default|policy)\b", re.IGNORECASE)),
    ("default-to-allow", re.compile(r"\bdefault(s|ed)?\s+to\s+allow\b", re.IGNORECASE)),
]

EXEMPT_MARKER = re.compile(r"FAIL_OPEN_OK:")
CONTEXT_WINDOW = 3

SCAN_DIRS = ["src", "user", "cambios-abi/src", "cambios-manifest/src"]


def iter_scan_paths():
    for rel in SCAN_DIRS:
        base = ROOT / rel
        if not base.is_dir():
            continue
        for path in sorted(base.glob("**/*.rs")):
            if "target" in path.parts:
                continue
            yield path


def has_exemption_near(lines, idx, window=CONTEXT_WINDOW):
    lo = max(0, idx - window)
    return bool(EXEMPT_MARKER.search("\n".join(lines[lo:idx + 1])))


def find_sites(path: Path):
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (UnicodeDecodeError, OSError):
        return
    for idx, line in enumerate(lines):
        for name, pat in PATTERNS:
            if pat.search(line):
                if has_exemption_near(lines, idx):
                    break
                yield (idx + 1, name, line.rstrip())
                break


def load_baseline():
    if not BASELINE_PATH.is_file():
        return set()
    entries = set()
    for raw in BASELINE_PATH.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(":", 2)
        if len(parts) == 3:
            entries.add((parts[0], parts[1], parts[2]))
    return entries


def main(argv):
    update = "--update-baseline" in argv
    found = []
    for path in iter_scan_paths():
        rel = path.relative_to(ROOT).as_posix()
        for lineno, name, text in find_sites(path):
            found.append((rel, str(lineno), name, text))

    if update:
        header = (
            "# Auto-generated by `make update-fail-open-baseline`.\n"
            "# Format: path:line:pattern (see tools/check-fail-open.py).\n"
            "#\n"
            "# Expected state: empty — enforcement fails closed (ADR-006\n"
            "# § Divergence 2026-10-28). Any non-comment line here is a\n"
            "# fail-open path someone decided to keep; its argument belongs\n"
            "# in the commit that added it.\n"
        )
        body = "".join(f"{rel}:{ln}:{name}\n" for rel, ln, name, _ in found)
        BASELINE_PATH.write_text(header + body, encoding="utf-8")
        print(f"check-fail-open: baseline written with {len(found)} entries")
        return 0

    baseline = load_baseline()
    new = [(rel, ln, name, text) for rel, ln, name, text in found if (rel, ln, name) not in baseline]
    print(f"check-fail-open: scanned; {len(found)} total flagged, {len(baseline)} baseline, {len(new)} new")
    if new:
        print()
        for rel, ln, name, text in new:
            print(f"  {rel}:{ln}: [{name}]")
            print(f"    > {text.strip()}")
        print()
        print("Enforcement fails closed. Either make the path deny (and audit), or")
        print("exempt the structural case with `// FAIL_OPEN_OK: <reason>` within 3")
        print("lines, or — only with an argument in the commit — append to")
        print("tools/check-fail-open-baseline.txt via `make update-fail-open-baseline`.")
        return 1
    print("check-fail-open OK: no new sites")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

"""
Pre-push gate: reject pushes containing Claude-authored commits whose
modified files were never observed in a Claude session's edit log.

Plan item (b) from ~/.claude/plans/threat-model-implementation.md.
Defense-in-depth on top of (a) sticky preflight (commit `e8957e2`):
(a) catches sweeps at commit time, (b) catches anything that slipped
through (a) — including bypass-via-`--no-verify` — at push time,
before the bad attribution leaves the local clone.

# How it works

Git invokes a pre-push hook with the line(s) of "<local_ref>
<local_oid> <remote_ref> <remote_oid>" on stdin. For each push
range, this script:

  1. Lists the commits being pushed (`git rev-list <remote>..<local>
     --not --remotes`: commits no remote-tracking ref has yet).
  2. For each commit with a `Co-Authored-By: Claude` trailer:
     a. Pulls the modified file list (`git diff-tree --no-commit-id
        --name-only -r <commit>`).
     b. Loads the union of every recorded edit log under
        `.git/claude-edit-log/*.jsonl`.
     c. Rejects if any committed file is not in the union — that
        file was never observed being edited by Claude in any
        session, so the commit is almost certainly sweeping a
        parallel session's hunks.

# Derived lockfiles

Cargo regenerates a `Cargo.lock` when an edit to its `Cargo.toml`
changes the dependency graph; no Edit/Write touches the lockfile,
so the edit log never sees it (f2a9991, 2026-11-22). A `Cargo.lock`
missing from the log is accepted as derived only when all of:

  1. its sibling `Cargo.toml` changed in the same commit, and that
     manifest is in the edit log;
  2. every changed line is a path-package line: `[[package]]`,
     `name = "…"`, `version = "…"`, `dependencies = [`, a `"…"`
     entry, `]`, or blank. A `source =` / `checksum =` line is a
     new or changed registry or git dependency: a supply-chain
     change, which a human reviews (the gate refuses it);
  3. cargo's header (the two `#` lines and `version = N`) appears
     only in a lockfile the commit creates.

Each acceptance prints a NOTICE naming the lockfile and its
manifest. The rule is `derived_lockfile`, a pure function; host
tests are `tools/test_check_edit_window.py` (`make test-tools`).

The "union of all sessions" check is intentionally loose: it
accepts a commit whose files were touched by *some* Claude
session, not necessarily *this* session. The single-session check
already happens at commit time via (a) sticky preflight, so by
the time we reach here the commit-to-session correspondence has
been verified once. The pre-push gate is the catch-anything
backstop.

# Gradual rollout

If no edit logs exist (CLAUDE_PREFLIGHT_SESSION never set, or
the PostToolUse hook isn't installed yet), this gate emits a
single NOTICE and exits 0. That keeps Jason's manual pushes and
pre-adoption Claude sessions unblocked. Once adoption is
universal, tighten the no-log branch to a hard error.

# Bypass

`git push --no-verify` (discouraged; the gate is meant to be
tripped, not silenced).

# Why a separate script + hook (not folded into commit-msg)

A pre-push gate fires *after* commits exist locally — so it
catches commits that bypassed the commit-msg phase via
`--no-verify`. A commit-msg gate cannot catch its own bypass;
a pre-push gate can. Together (a) and (b) form a defense in
depth where bypassing one still leaves the other in place.
"""
import json
import os
import posixpath
import re
import subprocess
import sys
from pathlib import Path


# A changed line a derived lockfile may contain: package bookkeeping for
# path dependencies only (no `source =` / `checksum =`). Matched against
# the line with its leading +/- removed.
LOCK_PACKAGE_LINE = re.compile(
    r'^(\[\[package\]\]|name = "[^"]+"|version = "[^"]+"'
    r'|dependencies = \[| "[^"]+",?|\]|)$'
)
# Cargo's lockfile header, accepted only in a newly created lockfile.
LOCK_HEADER_COMMENTS = (
    "# This file is automatically @generated by Cargo.",
    "# It is not intended for manual editing.",
)
LOCK_FORMAT_LINE = re.compile(r"^version = [0-9]+$")


def derived_lockfile(
    path: str,
    commit_changed: set[str],
    edit_union: set[str],
    diff_lines: list[str],
    created: bool,
) -> bool:
    """Whether `path` is a lockfile Cargo regenerated from an edit the
    log recorded (see "Derived lockfiles" above). Pure: the caller
    supplies the commit's changed files, the edit log union, the
    lockfile's changed lines (each starting with `+` or `-`, no
    `+++`/`---` headers) and whether the commit creates the file.
    Fails closed: anything not positively matched is not derived."""
    if posixpath.basename(path) != "Cargo.lock":
        return False
    manifest = posixpath.join(posixpath.dirname(path), "Cargo.toml")
    if manifest not in commit_changed or manifest not in edit_union:
        return False
    if not diff_lines:
        return False  # listed but no content change (mode only): review it
    for line in diff_lines:
        sign, body = line[:1], line[1:]
        if sign not in ("+", "-"):
            return False
        if LOCK_PACKAGE_LINE.match(body):
            continue
        if created and sign == "+" and (
            body in LOCK_HEADER_COMMENTS or LOCK_FORMAT_LINE.match(body)
        ):
            continue
        return False
    return True


def lockfile_diff(commit: str, path: str) -> tuple[list[str], bool]:
    """The changed lines of `path` in `commit` (zero context) and
    whether the commit creates it."""
    out = subprocess.check_output(
        ["git", "show", "--format=", "--unified=0", "--no-color", commit, "--", path],
        text=True,
    )
    lines = [
        l for l in out.splitlines()
        if l[:1] in ("+", "-") and not l.startswith(("+++", "---"))
    ]
    created = bool(
        subprocess.check_output(
            ["git", "diff-tree", "--no-commit-id", "--name-only", "-r",
             "--diff-filter=A", commit, "--", path],
            text=True,
        ).strip()
    )
    return lines, created


# Sentinel oids git uses for "branch creation" (no remote yet) and
# "branch deletion" (no local). On creation we have no remote_oid
# baseline; fall back to inspecting the full new branch range.
ZERO_OID = "0" * 40


def repo_root() -> Path:
    return Path(
        subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"], text=True
        ).strip()
    )


def load_edit_log_union(repo: Path) -> set[str]:
    """Return the set of repo-relative paths recorded across ALL
    `.git/claude-edit-log/*.jsonl` files. Robust against malformed
    lines (skip and continue)."""
    log_dir = repo / ".git" / "claude-edit-log"
    if not log_dir.is_dir():
        return set()

    union: set[str] = set()
    for path in log_dir.glob("*.jsonl"):
        try:
            with path.open("r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    file_path = rec.get("file")
                    if isinstance(file_path, str):
                        union.add(file_path)
        except OSError:
            continue
    return union


def commit_is_claude(commit: str) -> bool:
    msg = subprocess.check_output(
        ["git", "log", "-1", "--format=%B", commit], text=True
    )
    return "Co-Authored-By: Claude" in msg


def commit_files(commit: str) -> list[str]:
    out = subprocess.check_output(
        ["git", "diff-tree", "--no-commit-id", "--name-only", "-r", commit],
        text=True,
    ).strip()
    return out.splitlines() if out else []


def commits_in_range(local_oid: str, remote_oid: str) -> list[str]:
    """Walk commits being pushed. On branch creation (remote == zero
    oid), inspect the entire new branch; on an update, the commits
    after the remote's tip. Either way, only commits not yet reachable
    from any remote-tracking ref: a commit some remote already has was
    published once, and checking it again only re-fires on history (a
    push to the sandbox exchange re-checked the batch already on
    origin/main, 2026-11-19)."""
    if remote_oid == ZERO_OID:
        rev_args = ["git", "rev-list", local_oid, "--not", "--remotes"]
    elif local_oid == ZERO_OID:
        # Branch deletion — nothing being pushed forward to inspect.
        return []
    else:
        rev_args = ["git", "rev-list", f"{remote_oid}..{local_oid}", "--not", "--remotes"]
    out = subprocess.check_output(rev_args, text=True).strip()
    return out.splitlines() if out else []


def main() -> int:
    repo = repo_root()
    edit_union = load_edit_log_union(repo)

    # Read the pre-push protocol stdin: lines of
    #   <local_ref> <local_oid> <remote_ref> <remote_oid>
    push_lines = sys.stdin.read().splitlines()

    violations: list[tuple[str, str, list[str]]] = []
    derived: list[tuple[str, str]] = []
    saw_any_claude_commit = False

    for line in push_lines:
        if not line.strip():
            continue
        parts = line.split()
        if len(parts) < 4:
            continue
        local_ref, local_oid, _remote_ref, remote_oid = parts[:4]
        if local_oid == ZERO_OID:
            continue  # branch deletion — nothing to inspect

        for commit in commits_in_range(local_oid, remote_oid):
            try:
                if not commit_is_claude(commit):
                    continue
            except subprocess.CalledProcessError:
                continue
            saw_any_claude_commit = True

            try:
                files = commit_files(commit)
            except subprocess.CalledProcessError:
                continue

            changed = set(files)
            missing = []
            for f in files:
                if f in edit_union:
                    continue
                if posixpath.basename(f) == "Cargo.lock":
                    try:
                        diff_lines, created = lockfile_diff(commit, f)
                    except subprocess.CalledProcessError:
                        diff_lines, created = [], False
                    if derived_lockfile(f, changed, edit_union, diff_lines, created):
                        derived.append((commit, f))
                        continue
                missing.append(f)
            if missing:
                violations.append((commit, local_ref, missing))

    if not saw_any_claude_commit:
        return 0  # nothing Claude-authored in this push

    if not edit_union:
        # Claude commits being pushed but no edit log recorded — the
        # PostToolUse hook isn't installed yet, or the session never
        # set CLAUDE_PREFLIGHT_SESSION. Warn and pass.
        print(
            "NOTICE: pre-push edit-window check found Claude-authored",
            file=sys.stderr,
        )
        print(
            "  commits but no .git/claude-edit-log/*.jsonl entries.",
            file=sys.stderr,
        )
        print(
            "  Configure the PostToolUse hook in .claude/settings.local.json",
            file=sys.stderr,
        )
        print(
            "  and set CLAUDE_PREFLIGHT_SESSION per Claude session to enable",
            file=sys.stderr,
        )
        print(
            "  this gate. See ~/.claude/plans/threat-model-implementation.md.",
            file=sys.stderr,
        )
        return 0

    for commit, f in derived:
        short = subprocess.check_output(
            ["git", "log", "-1", "--format=%h", commit], text=True
        ).strip()
        manifest = posixpath.join(posixpath.dirname(f), "Cargo.toml")
        print(
            f"NOTICE: {short}: accepted {f} as derived from {manifest} "
            "(path-package lines only; see check-edit-window.py "
            "\"Derived lockfiles\").",
            file=sys.stderr,
        )

    if not violations:
        return 0

    print("ERROR: pre-push edit-window violation.", file=sys.stderr)
    print("", file=sys.stderr)
    print(
        "  These Claude-authored commits modify files that no Claude",
        file=sys.stderr,
    )
    print(
        "  session ever touched via Edit / Write / NotebookEdit:",
        file=sys.stderr,
    )
    print("", file=sys.stderr)
    for commit, local_ref, missing in violations:
        subj = subprocess.check_output(
            ["git", "log", "-1", "--format=%h %s", commit], text=True
        ).strip()
        print(f"  {subj} (on {local_ref})", file=sys.stderr)
        for f in missing:
            print(f"      {f}", file=sys.stderr)
        print("", file=sys.stderr)
    if any(posixpath.basename(f) == "Cargo.lock" for _, _, m in violations for f in m):
        print(
            "  A Cargo.lock passes only as derived: its sibling Cargo.toml",
            file=sys.stderr,
        )
        print(
            "  changed in the same commit and is in the edit log, and only",
            file=sys.stderr,
        )
        print(
            "  path-package lines changed. A `source =` / `checksum =` line",
            file=sys.stderr,
        )
        print(
            "  is a registry or git dependency change: review it by hand.",
            file=sys.stderr,
        )
        print("", file=sys.stderr)
    print(
        "  Almost-certain cause: a parallel Claude session's uncommitted",
        file=sys.stderr,
    )
    print(
        "  hunks were swept into one of these commits. The local commit",
        file=sys.stderr,
    )
    print(
        "  is wrong; rewriting before push is far cheaper than rewriting",
        file=sys.stderr,
    )
    print("  after.", file=sys.stderr)
    print("", file=sys.stderr)
    print(
        "  To recover: `git rebase -i <base>`, drop or amend the offending",
        file=sys.stderr,
    )
    print(
        "  commit so its file list matches what your session actually",
        file=sys.stderr,
    )
    print(
        "  edited. Coordinate with the parallel session if needed.",
        file=sys.stderr,
    )
    print("", file=sys.stderr)
    print(
        "  Bypass: `git push --no-verify` (discouraged).",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
